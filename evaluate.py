def load_input(
    input_path: Path,
) -> list[dict[str, Any]]:

    if not input_path.exists():
        raise FileNotFoundError(
            f"Файл не найден: {input_path}"
        )

    with input_path.open(
        "r",
        encoding="utf-8-sig",
    ) as file:
        data = json.load(file)

    if not isinstance(data, list):
        raise ValueError(
            "Ожидался JSON-массив объектов."
        )

    for index, item in enumerate(data):
        if not isinstance(item, dict):
            raise ValueError(
                f"Элемент {index} должен быть JSON-объектом."
            )

    return data


def validate_input(
    data: list[dict[str, Any]],
    input_field: str,
):
    if not data:
        raise ValueError(
            "Входной JSON-массив пуст."
        )

    missing_ids = [
        index
        for index, item in enumerate(data)
        if (
            not isinstance(item.get("id"), str)
            or not item["id"].strip()
        )
    ]

    if missing_ids:
        raise ValueError(
            "В объектах отсутствует корректный id. "
            f"Индексы: {missing_ids[:10]}"
        )

    duplicate_ids = set()
    seen_ids = set()

    for item in data:
        item_id = item["id"]

        if item_id in seen_ids:
            duplicate_ids.add(item_id)

        seen_ids.add(item_id)

    if duplicate_ids:
        raise ValueError(
            "Обнаружены повторяющиеся id во входном файле: "
            f"{list(duplicate_ids)[:10]}"
        )

    missing_gold = [
        index
        for index, item in enumerate(data)
        if not isinstance(item.get("result"), list)
    ]

    if missing_gold:
        raise ValueError(
            "В объектах отсутствует корректный список result. "
            f"Индексы: {missing_gold[:10]}"
        )

    missing_input = [
        index
        for index, item in enumerate(data)
        if input_field not in item
    ]

    if missing_input:
        raise ValueError(
            f"В объектах отсутствует поле '{input_field}'. "
            f"Индексы: {missing_input[:10]}"
        )


# ============================================================
# SINGLE RECORD EVALUATION
# ============================================================

def evaluate_record(
    row_index: int,
    user_prompt: str,
    system_prompt: str,
    args,
) -> dict[str, Any]:

    result = {
        "row_index": row_index,
        "llm_result": None,
        "llm_raw": "",
        "llm_error": "",
        "llm_attempts": 0,
    }

    if (
        not isinstance(user_prompt, str)
        or not user_prompt.strip()
    ):
        result["llm_error"] = (
            f"Пустое поле {args.input_field}."
        )
        return result

    last_error = None

    for attempt in range(1, MAX_RETRIES + 1):
        result["llm_attempts"] = attempt

        try:
            client = get_client(args)

            raw_response = client.invoke(
                system_prompt=system_prompt,
                user_prompt=user_prompt,
            )

            result["llm_raw"] = raw_response

            result["llm_result"] = parse_response(
                raw_response
            )

            result["llm_error"] = ""

            return result

        except Exception as exc:
            last_error = exc

            logger.warning(
                "Объект %s | попытка %s/%s | ошибка: %s",
                row_index,
                attempt,
                MAX_RETRIES,
                exc,
            )

            reset_client()

            if attempt < MAX_RETRIES:
                delay = RETRY_DELAYS[
                    min(
                        attempt - 1,
                        len(RETRY_DELAYS) - 1,
                    )
                ]

                time.sleep(delay)

    result["llm_error"] = str(last_error)

    return result


