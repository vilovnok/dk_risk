# ATOMIC JSON SAVE
# ============================================================

def atomic_save_json(
    data: Any,
    output_path: Path,
):
    """Атомарно сохраняет JSON-объект или массив."""

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    temp_path = output_path.with_name(
        output_path.stem + ".tmp" + output_path.suffix
    )

    try:
        with temp_path.open(
            "w",
            encoding="utf-8",
        ) as file:
            json.dump(
                data,
                file,
                ensure_ascii=False,
                indent=2,
            )

        temp_path.replace(output_path)

    finally:
        if temp_path.exists():
            temp_path.unlink()


def append_json_results(
    records: list[dict[str, Any]],
    output_path: Path,
) -> int:
    """
    Добавляет результаты в JSON.

    Уникальность:
        id + model + timestamp.

    Существующие результаты других запусков сохраняются.
    """

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    if output_path.exists():
        with output_path.open(
            "r",
            encoding="utf-8",
        ) as file:
            existing = json.load(file)

        if not isinstance(existing, list):
            raise ValueError(
                f"Ожидался JSON-массив: {output_path}"
            )

    else:
        existing = []

    existing_keys = {
        (
            item.get("id"),
            item.get("model"),
            item.get("timestamp"),
        )
        for item in existing
        if isinstance(item, dict)
    }

    added = 0

    for record in records:
        key = (
            record["id"],
            record["model"],
            record["timestamp"],
        )

        if key in existing_keys:
            continue

        existing.append(record)
        existing_keys.add(key)
        added += 1

    if added:
        atomic_save_json(
            existing,
            output_path,
        )

    return added


