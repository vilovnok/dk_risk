def parse_args():

    parser = argparse.ArgumentParser(
        description=(
            "Многопоточная оценка JSON-диалогов "
            "с расчётом Exact Match Accuracy."
        )
    )

    parser.add_argument(
        "--input",
        required=True,
        help="Путь к входному prepared JSON.",
    )

    parser.add_argument(
        "--output",
        default="pool_2_prepared.csv",
        help="Путь к итоговому CSV.",
    )

    parser.add_argument(
        "--json-output",
        default="pool_2_prepared.json",
        help="Путь к подробному JSON.",
    )

    parser.add_argument(
        "--input-field",
        default=INPUT_FIELD,
        help="Поле JSON с текстом для LLM.",
    )

    parser.add_argument(
        "-w",
        "--workers",
        type=int,
        default=5,
        help="Количество потоков.",
    )

    parser.add_argument(
        "--provider",
        choices=["aihf", "direct", "sigma"],
        default="aihf",
    )

    parser.add_argument(
        "--model",
        default=DEFAULT_MODEL,
    )

    parser.add_argument(
        "--temperature",
        type=float,
        default=DEFAULT_TEMPERATURE,
    )

    parser.add_argument(
        "--top-p",
        type=float,
        default=DEFAULT_TOP_P,
    )

    args = parser.parse_args()

    if args.workers < 1:
        parser.error(
            "--workers должен быть не меньше 1."
        )

    if not 0 <= args.temperature <= 2:
        parser.error(
            "--temperature должен быть в диапазоне 0..2."
        )

    if not 0 < args.top_p <= 1:
        parser.error(
            "--top-p должен быть в диапазоне (0, 1]."
        )

    return args


