# ============================================================

def evaluate_record(
    row_index: int,
    user_prompt: str,
    system_prompt: str,
    args,
) -> dict:
    result = {
        "row_index": row_index,
        "llm_result": None,
        "llm_raw": "",
        "llm_error": "",
        "llm_attempts": 0,
    }

    if not isinstance(user_prompt, str) or not user_prompt.strip():
        result["llm_error"] = "Пустое поле part_system_prompt."
        return result

    last_error = None

    for attempt in range(1, MAX_RETRIES + 1):
        result["llm_attempts"] = attempt

        try:
            client = get_client(args)
            raw_response = client.invoke(
                system_prompt=system_prompt,
                user_prompt=user_prompt,
            )

            result["llm_raw"] = raw_response
            result["llm_result"] = parse_response(raw_response)
            result["llm_error"] = ""
            return result

        except Exception as exc:
            last_error = exc
            logger.warning(
                "Объект %s | попытка %s/%s | ошибка: %s",
                row_index,
                attempt,
                MAX_RETRIES,
                exc,
            )
            reset_client()

            if attempt < MAX_RETRIES:
                delay = RETRY_DELAYS[
                    min(attempt - 1, len(RETRY_DELAYS) - 1)
                ]
                time.sleep(delay)

    result["llm_error"] = str(last_error)
    return result


