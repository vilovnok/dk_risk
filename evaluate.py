class GigaChatClient:

    def __init__(
        self,
        provider: str,
        model: str,
        temperature: float,
        top_p: float,
    ):
        if provider not in ENDPOINTS:
            raise ValueError(
                f"Неизвестный provider: {provider}"
            )

        self.provider = provider
        self.model = model
        self.temperature = temperature
        self.top_p = top_p
        self.url = ENDPOINTS[provider]

        self.session = requests.Session()
        self.token = self._get_token()

    def _get_token(self) -> str:
        config_path = os.path.expanduser(
            CFG[self.provider]
        )

        client = TagmeClientAdvanced(config_path)
        token = client.client.token

        if not token:
            raise RuntimeError(
                f"Не удалось получить токен для {self.provider}"
            )

        return token

    def invoke(
        self,
        system_prompt: str,
        user_prompt: str,
    ) -> str:

        # Формируем payload один раз.
        # При повторных отправках содержимое запроса не меняется.
        payload = {
            "model": self.model,
            "messages": [
                {
                    "role": "system",
                    "content": system_prompt,
                },
                {
                    "role": "user",
                    "content": user_prompt,
                },
            ],
            "temperature": self.temperature,
            "top_p": self.top_p,
            "max_tokens": MAX_TOKENS,
            "profanity_check": False,
        }

        # Внутренний цикл нужен для обработки 401.
        # Если обновление токена не помогло, исключение
        # попадёт во внешний цикл повторных попыток.
        headers = {
            "Authorization": f"Bearer {self.token}",
            "Content-Type": "application/json",
        }

        response = self.session.post(
            self.url,
            headers=headers,
            json=payload,
            verify=False,
            timeout=TIMEOUT,
        )

        if response.status_code == 401:
            logger.warning(
                "HTTP 401. Обновляю токен и повторяю тот же запрос."
            )

            self.token = self._get_token()

            headers["Authorization"] = (
                f"Bearer {self.token}"
            )

            response = self.session.post(
                self.url,
                headers=headers,
                json=payload,
                verify=False,
                timeout=TIMEOUT,
            )

        response.raise_for_status()

        data = response.json()

        try:
            content = data["choices"][0]["message"]["content"]

        except (KeyError, IndexError, TypeError) as exc:
            raise RuntimeError(
                f"Не удалось извлечь ответ модели: {data}"
            ) from exc

        if isinstance(content, list):
            content = "".join(
                item.get("text", "")
                for item in content
                if isinstance(item, dict)
            )

        if not isinstance(content, str) or not content.strip():
            raise RuntimeError(
                "Модель вернула пустой ответ."
            )

        return content.strip()


