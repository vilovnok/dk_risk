def run_evaluation(args):

    input_path = Path(args.input)
    csv_path = Path(args.output)
    json_path = Path(args.json_output)
    prompt_path = Path(args.system_prompt_file)
    full_predictions_path = Path(args.full_predictions_output)

    data = load_input(input_path)

    validate_input(
        data=data,
        input_field=args.input_field,
    )

    system_prompt = load_system_prompt()

    total_rows = len(data)

    timestamp = datetime.now().astimezone().isoformat(
        timespec="seconds"
    )

    logger.info("=" * 70)
    logger.info("ЗАПУСК ОЦЕНКИ")
    logger.info("=" * 70)

    logger.info("Входной файл: %s", input_path)
    logger.info("Системный промпт: %s", prompt_path)
    logger.info("Выходной CSV: %s", csv_path)
    logger.info("Выходной JSON: %s", json_path)
    logger.info("Количество объектов: %s", total_rows)
    logger.info("Поле для LLM: %s", args.input_field)
    logger.info("Provider: %s", args.provider)
    logger.info("Модель: %s", args.model)
    logger.info("Workers: %s", args.workers)
    logger.info("Timestamp: %s", timestamp)
    logger.info(
    "Полные ответы модели: %s",
    full_predictions_path,
)

    results: dict[int, dict[str, Any]] = {}
    futures = {}

    written_indices: set[int] = set()

    completed = 0
    successful = 0
    failed = 0

    with ThreadPoolExecutor(
        max_workers=args.workers
    ) as executor:

        for index, item in enumerate(data):

            user_prompt = item.get(
                args.input_field
            )

            future = executor.submit(
                evaluate_record,
                index,
                user_prompt,
                system_prompt,
                args,
            )

            futures[future] = index

        for future in as_completed(futures):

            index = futures[future]

            try:
                result = future.result()

            except Exception as exc:
                result = {
                    "row_index": index,
                    "llm_result": None,
                    "llm_raw": "",
                    "llm_error": str(exc),
                    "llm_attempts": 0,
                }

            results[index] = result
            completed += 1

            if result["llm_error"]:
                failed += 1
            else:
                successful += 1

            if completed % CHECKPOINT_EVERY == 0:

                pending_indices = sorted(
                    set(results.keys()) - written_indices
                )

                csv_saved, json_saved, full_saved = save_checkpoint(
                    data=data,
                    results=results,
                    row_indices=pending_indices,
                    csv_path=csv_path,
                    json_path=json_path,
                    full_predictions_path=full_predictions_path,
                    model=args.model,
                    timestamp=timestamp,
                )

                written_indices.update(
                    pending_indices
                )

                logger.info(
                    "Прогресс: %s/%s | Успешно: %s | "
                    "Ошибки: %s | CSV: +%s | JSON: +%s | Full: +%s",
                    completed,
                    total_rows,
                    successful,
                    failed,
                    csv_saved,
                    json_saved,
                    full_saved,
                )


    # Финальное сохранение.
    pending_indices = sorted(
        set(results.keys()) - written_indices
    )

    csv_saved, json_saved, full_saved = save_checkpoint(
        data=data,
        results=results,
        row_indices=pending_indices,
        csv_path=csv_path,
        json_path=json_path,
        full_predictions_path=full_predictions_path,
        model=args.model,
        timestamp=timestamp,
    )

    written_indices.update(
        pending_indices
    )

    metrics = calculate_metrics(
        data=data,
        results=results,
    )

    log_metrics(metrics)

    logger.info(
        "Добавлено строк в CSV при финальном сохранении: %s",
        csv_saved,
    )

    logger.info(
        "Добавлено записей в JSON при финальном сохранении: %s",
        json_saved,
    )

    logger.info(
        "Итоговый CSV: %s",
        csv_path,
    )

    logger.info(
        "Итоговый JSON: %s",
        json_path,
    )
    logger.info(
        "Добавлено полных предсказаний при финальном сохранении: %s",
        full_saved,
    )

    logger.info(
        "Итоговый файл полных предсказаний: %s",
        full_predictions_path,
    )

    logger.info("=" * 70)
    logger.info("ОБРАБОТКА ЗАВЕРШЕНА")
    logger.info("=" * 70)


