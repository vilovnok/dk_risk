# MAIN EVALUATION
# ============================================================

def run_evaluation(args):

    input_path = Path(args.input)
    csv_path = Path(args.output)
    json_path = Path(args.json_output)

    data = load_input(input_path)

    validate_input(
        data=data,
        input_field=args.input_field,
    )

    # Проверяем наличие системного промпта.
    if not isinstance(SYSTEM_PROMPT, str) or not SYSTEM_PROMPT.strip():
        raise ValueError(
            "SYSTEM_PROMPT не определён или пуст."
        )

    total_rows = len(data)

    timestamp = datetime.now().astimezone().isoformat(
        timespec="seconds"
    )

    logger.info("=" * 70)
    logger.info("ЗАПУСК ОЦЕНКИ")
    logger.info("=" * 70)

    logger.info("Входной файл: %s", input_path)
    logger.info("Выходной CSV: %s", csv_path)
    logger.info("Выходной JSON: %s", json_path)
    logger.info("Количество объектов: %s", total_rows)
    logger.info("Поле для LLM: %s", args.input_field)
    logger.info("Provider: %s", args.provider)
    logger.info("Модель: %s", args.model)
    logger.info("Workers: %s", args.workers)
    logger.info("Timestamp: %s", timestamp)

    results: dict[int, dict[str, Any]] = {}
    futures = {}

    # Индексы, которые уже сохранены в рамках этого запуска.
    written_indices: set[int] = set()

    completed = 0
    successful = 0
    failed = 0

    with ThreadPoolExecutor(
        max_workers=args.workers
    ) as executor:

        for index, item in enumerate(data):

            user_prompt = item.get(
                args.input_field
            )

            if (
                not isinstance(user_prompt, str)
                or not user_prompt.strip()
            ):
                results[index] = {
                    "row_index": index,
                    "llm_result": None,
                    "llm_raw": "",
                    "llm_error": (
                        f"Пустое поле {args.input_field}."
                    ),
                    "llm_attempts": 0,
                }

                completed += 1
                failed += 1

                continue

            future = executor.submit(
                evaluate_record,
                index,
                user_prompt,
                SYSTEM_PROMPT,
                args,
            )

            futures[future] = index

        for future in as_completed(futures):

            index = futures[future]

            try:
                result = future.result()

            except Exception as exc:
                result = {
                    "row_index": index,
                    "llm_result": None,
                    "llm_raw": "",
                    "llm_error": str(exc),
                    "llm_attempts": 0,
                }

            results[index] = result
            completed += 1

            if result["llm_error"]:
                failed += 1
            else:
                successful += 1

            # Контрольное сохранение.
            if completed % CHECKPOINT_EVERY == 0:

                pending_indices = sorted(
                    set(results.keys()) - written_indices
                )

                csv_saved, json_saved = save_checkpoint(
                    data=data,
                    results=results,
                    row_indices=pending_indices,
                    csv_path=csv_path,
                    json_path=json_path,
                    model=args.model,
                    timestamp=timestamp,
                )

                written_indices.update(
                    pending_indices
                )

                logger.info(
                    "Прогресс: %s/%s | Успешно: %s | "
                    "Ошибки: %s | CSV: +%s | JSON: +%s",
                    completed,
                    total_rows,
                    successful,
                    failed,
                    csv_saved,
                    json_saved,
                )

    # Финальное сохранение.
    # Уже сохранённые при checkpoint записи не дублируются.
    pending_indices = sorted(
        set(results.keys()) - written_indices
    )

    csv_saved, json_saved = save_checkpoint(
        data=data,
        results=results,
        row_indices=pending_indices,
        csv_path=csv_path,
        json_path=json_path,
        model=args.model,
        timestamp=timestamp,
    )

    written_indices.update(
        pending_indices
    )

    metrics = calculate_metrics(
        data=data,
        results=results,
    )

    log_metrics(metrics)

    logger.info(
        "Добавлено строк в CSV при финальном сохранении: %s",
        csv_saved,
    )

    logger.info(
        "Добавлено записей в JSON при финальном сохранении: %s",
        json_saved,
    )

    logger.info(
        "Итоговый CSV: %s",
        csv_path,
    )

    logger.info(
        "Итоговый JSON: %s",
        json_path,
    )

    logger.info("=" * 70)
    logger.info("ОБРАБОТКА ЗАВЕРШЕНА")
    logger.info("=" * 70)


