# SINGLE RECORD EVALUATION
# ============================================================

def evaluate_record(
    row_index: int,
    user_prompt: str,
    system_prompt: str,
    args,
) -> dict[str, Any]:

    result = {
        "row_index": row_index,
        "llm_result": None,
        "llm_raw": "",
        "llm_error": "",
        "llm_attempts": 0,
    }

    # Проверяем входные критерии один раз.
    # Некорректные входные данные не исправятся повторной отправкой.
    try:
        expected_names = extract_expected_names(
            user_prompt=user_prompt,
            item_id=str(row_index),
        )

    except Exception as exc:
        result["llm_error"] = (
            f"Ошибка входных критериев: {exc}"
        )

        logger.error(
            "Объект %s | ошибка входных критериев: %s",
            row_index,
            exc,
        )

        return result

    for attempt in range(1, MAX_RETRIES + 1):
        result["llm_attempts"] = attempt

        try:
            client = get_client(args)

            # При каждой попытке отправляется тот же запрос.
            raw_response = client.invoke(
                system_prompt=system_prompt,
                user_prompt=user_prompt,
            )

            parsed_result = parse_response(
                raw_response=raw_response,
                expected_names=expected_names,
            )

            # Сохраняем только полностью проверенный результат.
            result["llm_raw"] = raw_response
            result["llm_result"] = parsed_result
            result["llm_error"] = ""

            logger.info(
                "Объект %s | успешно обработан | попыток: %s",
                row_index,
                attempt,
            )

            return result

        except KeyboardInterrupt:
            raise

        except Exception as exc:
            result["llm_error"] = str(exc)

            logger.warning(
                "Объект %s | попытка %s/%s | ошибка: %s",
                row_index,
                attempt,
                MAX_RETRIES,
                exc,
            )

            # Закрываем старый клиент.
            # Следующая попытка создаст новую сессию и получит токен.
            reset_client()

            if attempt < MAX_RETRIES:
                logger.warning(
                    "Объект %s | повторная отправка через %s секунды.",
                    row_index,
                    RETRY_DELAY,
                )

                time.sleep(RETRY_DELAY)

    logger.error(
        "Объект %s | не удалось обработать после %s попыток.",
        row_index,
        MAX_RETRIES,
    )

    return result

