# ============================================================

def atomic_save_json(
    data: list[dict[str, Any]],
    output_path: Path,
):
    """Атомарная запись JSON через временный файл."""

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    temp_path = output_path.with_name(
        output_path.stem + ".tmp" + output_path.suffix
    )

    try:
        with temp_path.open(
            "w",
            encoding="utf-8",
        ) as file:
            json.dump(
                data,
                file,
                ensure_ascii=False,
                indent=2,
            )

        temp_path.replace(output_path)

    finally:
        if temp_path.exists():
            temp_path.unlink()


def append_json_results(
    records: list[dict[str, Any]],
    output_path: Path,
) -> int:
    """
    Добавляет подробные результаты в JSON.

    Уникальность записи:
        id + model + timestamp.

    Существующие результаты других запусков сохраняются.
    """

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    if output_path.exists():
        with output_path.open(
            "r",
            encoding="utf-8",
        ) as file:
            existing = json.load(file)

        if not isinstance(existing, list):
            raise ValueError(
                f"Ожидался JSON-массив: {output_path}"
            )

    else:
        existing = []

    existing_keys = {
        (
            item.get("id"),
            item.get("model"),
            item.get("timestamp"),
        )
        for item in existing
        if isinstance(item, dict)
    }

    added = 0

    for record in records:
        key = (
            record["id"],
            record["model"],
            record["timestamp"],
        )

        if key in existing_keys:
            continue

        existing.append(record)
        existing_keys.add(key)
        added += 1

    if added:
        atomic_save_json(
            existing,
            output_path,
        )

    return added


# ============================================================
# CSV SAVE
# ============================================================

def append_csv_results(
    records: list[dict[str, Any]],
    output_path: Path,
) -> int:
    """Добавляет новые строки в CSV."""

    if not records:
        return 0

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    file_exists = (
        output_path.exists()
        and output_path.stat().st_size > 0
    )

    with output_path.open(
        "a",
        encoding="utf-8-sig",
        newline="",
    ) as file:

        writer = csv.DictWriter(
            file,
            fieldnames=CSV_FIELDS,
            extrasaction="ignore",
        )

        if not file_exists:
            writer.writeheader()

        writer.writerows(records)

    return len(records)


# ============================================================
# CHECKPOINT
# ============================================================

def save_checkpoint(
    data: list[dict[str, Any]],
    results: dict[int, dict[str, Any]],
    row_indices: list[int],
    csv_path: Path,
    json_path: Path,
    model: str,
    timestamp: str,
) -> tuple[int, int]:
    """Сохраняет новые результаты в CSV и JSON."""

    csv_records = []
    json_records = []

    for index in row_indices:
        original_item = data[index]
        llm_record = results.get(index)

        csv_records.append(
            build_csv_row(
                original_item=original_item,
                llm_record=llm_record,
                model=model,
                timestamp=timestamp,
            )
        )

        try:
            json_records.append(
                build_result_record(
                    original_item=original_item,
                    llm_record=llm_record,
                    model=model,
                    timestamp=timestamp,
                    row_index=index,
                )
            )

        except (ValueError, TypeError) as exc:
            logger.warning(
                "ID %s: не удалось сформировать JSON-запись: %s",
                original_item["id"],
                exc,
            )

    csv_saved = append_csv_results(
        records=csv_records,
        output_path=csv_path,
    )

    json_saved = append_json_results(
        records=json_records,
        output_path=json_path,
    )

    return csv_saved, json_saved


